-- BudgetRoleSyncAndLevelFk step 1 (D4): the Budget-only office levels in the EXISTING budget.levels master.
--
-- The hierarchy master holds CE, CR and Div (Chief Engineer, Circle and Division). Budget also authorises roles
-- at FINANCE, SECRETARIAT and IT_CELL, which have no hierarchy row. Each is inserted ONLY where no row of that
-- name exists (trimmed, case-insensitive), with status = false like the existing rows (status is the hierarchy
-- master's flag and Budget does not read it). Existing rows are never updated. Re-running inserts nothing.
-- The names are BudgetRoleLevel.BudgetOnlyLevelNames; the alias map (BudgetRoleLevel.Aliases) maps each to itself.
--
-- levels.id is GENERATED BY DEFAULT AS IDENTITY, so no id is given. Rows may have been loaded with explicit ids
-- without advancing the identity sequence (on the live database the sequence still stood at 1, not called, with
-- ids 1..3 taken), which would make the first insert collide with PK_levels. The sequence is therefore moved past
-- max(id) first, and only ever forward. setval is not rolled back if a later step aborts; an unused gap in the
-- sequence is harmless.
DO $levels$
DECLARE
    v_seq  text := pg_get_serial_sequence('budget.levels', 'id');
    v_next bigint;
    v_max  bigint;
BEGIN
    IF v_seq IS NULL THEN
        RAISE EXCEPTION 'BudgetRoleSyncAndLevelFk: budget.levels.id has no identity sequence';
    END IF;
    EXECUTE format('SELECT CASE WHEN is_called THEN last_value + 1 ELSE last_value END FROM %s', v_seq) INTO v_next;
    SELECT max(id) INTO v_max FROM budget.levels;
    IF v_max IS NOT NULL AND v_max >= v_next THEN
        PERFORM setval(v_seq, v_max + 1, false);
    END IF;
END
$levels$;

INSERT INTO budget.levels (name, status)
SELECT v.name, false
FROM (VALUES (1, 'FINANCE'), (2, 'SECRETARIAT'), (3, 'IT_CELL')) AS v(ord, name)
WHERE NOT EXISTS (SELECT 1 FROM budget.levels l WHERE upper(btrim(l.name)) = v.name)
ORDER BY v.ord;
